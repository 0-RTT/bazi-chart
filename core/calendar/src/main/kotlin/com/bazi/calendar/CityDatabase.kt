    /** 省份顺序：按行政大区习惯，直辖市在前，其后各省。 */
    val provinces: List<String> = cities.map { it.province }.distinct()

    val default: City = cities.first { it.name == "北京" }

    fun search(keyword: String, province: String? = null): List<City> {
        val scoped = if (province == null) cities else cities.filter { it.province == province }
        if (keyword.isBlank()) return scoped
        val k = keyword.trim()
        return scoped.filter { it.name.contains(k) || it.province.contains(k) }
    }

    /**
     * 就近城市：定位取到经纬度后，用来给用户一个眼熟的地名。
     *
     * 用球面距离（haversine）而不是平面距离——跨纬度时平面近似会把
     * 经度方向拉长，东北与西南的城市容易被判到隔壁省份。
     */
    fun nearest(longitude: Double, latitude: Double): City =
        cities.minBy { haversine(it.longitude, it.latitude, longitude, latitude) }

    private fun haversine(lon1: Double, lat1: Double, lon2: Double, lat2: Double): Double {
        val r = 6371.0
        val dLat = Math.toRadians(lat2 - lat1)
        val dLon = Math.toRadians(lon2 - lon1)
        val a = Math.sin(dLat / 2) * Math.sin(dLat / 2) +
            Math.cos(Math.toRadians(lat1)) * Math.cos(Math.toRadians(lat2)) *
            Math.sin(dLon / 2) * Math.sin(dLon / 2)
        return 2 * r * Math.asin(Math.sqrt(a))
    }
